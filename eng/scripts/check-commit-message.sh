#!/usr/bin/env bash
# Validates a commit message (or PR title/body) against the repository rules in
# docs/process/development-workflow.md, section 5:
#   1. no AI attribution of any kind (co-author trailers, "generated with" markers);
#   2. optionally, the first line follows Conventional Commits.
#
# usage: check-commit-message.sh [--subject] <file>
#   --subject  also enforce the Conventional Commits subject line format
# exit codes: 0 ok, 1 rule violated, 2 usage error
set -euo pipefail

check_subject=false
if [[ "${1:-}" == "--subject" ]]; then
    check_subject=true
    shift
fi
file="${1:-}"
if [[ -z "$file" || ! -f "$file" ]]; then
    echo "usage: $0 [--subject] <message-file>" >&2
    exit 2
fi

# Lines git itself strips (comments) must not trigger a false positive.
message="$(grep -v '^#' "$file" || true)"
status=0

ai_names='claude|anthropic|chatgpt|openai|copilot|gemini|codex|cursor|devin|windsurf|tabnine|codeium'
if grep -Eiq "^[[:space:]]*co-authored-by:.*(${ai_names}|noreply@anthropic\.com)" <<<"$message"; then
    echo "error: AI co-author trailer found. AI attribution is not allowed in this repository." >&2
    status=1
fi
# The AI name must directly follow "generated with/by" (optionally "[", "the", "an"), so
# ordinary prose such as "output generated by the bridge for AI agents" is not flagged.
if grep -Eiq "(generated|created|written|authored)[[:space:]]+(with|by|using)[[:space:]]+\[?((the|an?)[[:space:]]+)?(${ai_names}|ai([^[:alpha:]]|$))" <<<"$message"; then
    echo "error: 'generated with/by AI' marker found. AI attribution is not allowed in this repository." >&2
    status=1
fi
if grep -q $'\xF0\x9F\xA4\x96' <<<"$message"; then
    echo "error: robot emoji marker found. AI attribution is not allowed in this repository." >&2
    status=1
fi

if [[ "$check_subject" == true ]]; then
    subject="$(head -n 1 <<<"$message")"
    pattern='^(feat|fix|docs|refactor|perf|test|build|ci|chore|revert)(\([a-z0-9-]+\))?!?: .+$'
    if ! grep -Eq "$pattern" <<<"$subject"; then
        echo "error: subject is not a Conventional Commit: '$subject'" >&2
        echo "       expected: type(scope): summary   e.g. feat(tools): add eplan_page_create" >&2
        status=1
    elif (( ${#subject} > 72 )); then
        echo "error: subject is ${#subject} characters; keep it within 72." >&2
        status=1
    fi
fi

exit "$status"
