<#
.SYNOPSIS
    Writes the Workbench palettes' v2 colour blocks from the design tokens (ADR-0034 decision 6).
.DESCRIPTION
    src/EplanMcp.Workbench/Themes/tokens.json is the design system's export ("EplanMcp Workbench 设计规范") and
    tokens.map.json says which vendored Primer/Ant key takes which token, per theme where a theme differs. The script
    rewrites the block between the BEGIN/END markers in Palette.Light.xaml and Palette.Dark.xaml; high contrast follows
    the system colours and is not generated. A design change edits tokens.json (and the map when a key moves) and runs
    this script; ThemeTokensJsonTests fails while a palette is out of date.
.EXAMPLE
    eng\scripts\workbench-tokens.ps1
#>
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$themes = Join-Path $PSScriptRoot '..\..\src\EplanMcp.Workbench\Themes'
$tokens = @{}
foreach ($token in (Get-Content (Join-Path $themes 'tokens.json') -Raw -Encoding utf8 | ConvertFrom-Json).color.tokens) {
    $tokens[$token.name] = $token.value
}
$map = Get-Content (Join-Path $themes 'tokens.map.json') -Raw -Encoding utf8 | ConvertFrom-Json -AsHashtable

# '#RRGGBB', '#RRGGBBAA' or 'rgba(r,g,b,a)' to WPF's '#AARRGGBB' (or '#RRGGBB' when opaque).
function ConvertTo-WpfColor([string] $value) {
    $v = $value -replace '\s', ''
    if ($v -match '^rgba\(([\d.]+),([\d.]+),([\d.]+),([\d.]+)\)$') {
        $a = [int][math]::Round([double]$Matches[4] * 255)
        return '#{0:X2}{1:X2}{2:X2}{3:X2}' -f $a, [int][double]$Matches[1], [int][double]$Matches[2], [int][double]$Matches[3]
    }
    $hex = $v.TrimStart('#').ToUpperInvariant()
    if ($hex.Length -eq 8) { return '#' + $hex.Substring(6, 2) + $hex.Substring(0, 6) }
    if ($hex.Length -eq 6) { return '#' + $hex }
    throw "Unsupported colour '$value'."
}

foreach ($theme in 'light', 'dark') {
    $keys = [ordered]@{}
    foreach ($key in $map.all.Keys) { $keys[$key] = $map.all[$key] }
    if ($map.ContainsKey($theme)) { foreach ($key in $map[$theme].Keys) { $keys[$key] = $map[$theme][$key] } }
    $ordered = $keys.Keys | Sort-Object { -not $_.StartsWith('Primer.') }, { $_ } -CaseSensitive
    $lines = foreach ($key in $ordered) {
        $name = $keys[$key]
        if (-not $tokens.ContainsKey($name)) { throw "tokens.map.json names '$name', which tokens.json does not have." }
        '  <SolidColorBrush x:Key="{0}" Color="{1}" /><!-- {2} -->' -f $key, (ConvertTo-WpfColor $tokens[$name].$theme), $name
    }
    $file = Join-Path $themes ("Palette.{0}.xaml" -f (Get-Culture).TextInfo.ToTitleCase($theme))
    $text = [IO.File]::ReadAllText($file)
    $begin = '  <!-- BEGIN v2 tokens: generated by eng/scripts/workbench-tokens.ps1 from tokens.json; do not edit by hand. -->'
    $end = '  <!-- END v2 tokens -->'
    $at = $text.IndexOf($begin); $until = $text.IndexOf($end)
    if ($at -lt 0 -or $until -lt $at) { throw "$file has no BEGIN/END v2 tokens block." }
    $block = $begin + "`n" + ($lines -join "`n") + "`n" + $end
    [IO.File]::WriteAllText($file, $text.Substring(0, $at) + $block + $text.Substring($until + $end.Length), [Text.UTF8Encoding]::new($false))
    "Wrote $($ordered.Count) colours to $(Split-Path $file -Leaf)."
}
