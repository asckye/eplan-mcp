using System.Text.Json;
using EplanMcp.Host.Tools;
namespace EplanMcp.Coverage;
/// <summary>Catalog-derived closed dispatch. Extend the reviewed type/member selection, never runtime reflection.</summary>
internal static class ApiTryGenerator
{
    internal const string CatalogPath = "src/EplanMcp.Contracts/Generated/ApiTryCatalog.g.cs";
    internal const string DispatchPath = "src/EplanMcp.Bridge.Eplan/Adapters/ApiTryDispatch.g.cs";
    private static string Literal(string value) => JsonSerializer.Serialize(value);
    internal static IEnumerable<(ApiEntry Entry, ApiDetail Member)> Selected(ApiIndexData data) => data.Entries
        .Where(e => e.Row.ExcludedReason is null && e.Type is "T:Eplan.EplApi.DataModel.Page" or "T:Eplan.EplApi.DataModel.Function" or "T:Eplan.EplApi.DataModel.Connection")
        .SelectMany(e => e.Details.Where(d => d.Kind == "overload" && d.ExcludedReason is null && !d.Static
            && (d.ReturnType is "System.String" or "System.Boolean" or "System.Double" or "System.Int32" or "System.Int64")
            && (e.Row.Kind == "property" && d.Accessors?.Contains("get", StringComparison.Ordinal) == true && d.Parameters is { Length: 0 }
                || d.Id == "M:Eplan.EplApi.DataModel.Function.IsDeviceLocked(System.Boolean)"))
            .Select(d => (e, d)));
    internal static string Catalog(string root)
    {
        ApiIndexData data = ApiIndexGenerator.Data(root);
        return "// <auto-generated/>\n#nullable enable\nnamespace EplanMcp.Contracts;\npublic static class ApiTryCatalog\n{\n"
            + "    public static bool Allowed(string group) => group switch\n    {\n"
            + string.Join("\n", data.Entries.Where(e => e.Row.ExcludedReason is null && e.Row.Kind is "method" or "property").Select(e => "        " + Literal(e.Row.Group) + " => true,"))
            + "\n        _ => false,\n    };\n    public static string[]? Shape(string group) => group switch\n    {\n"
            + string.Join("\n", Selected(data).Select(s => "        " + Literal(s.Entry.Row.Group) + " => [" + string.Join(", ", new[] { s.Entry.Type[2..], s.Member.Signature! }.Concat(s.Member.Parameters!.Select(p => p.Name)).Select(Literal)) + "],"))
            + "\n        _ => null,\n    };\n}\n";
    }
    internal static string Dispatch(string root) => "// <auto-generated/>\n#nullable enable\nusing Eplan.EplApi.DataModel;\nusing Newtonsoft.Json.Linq;\nnamespace EplanMcp.Bridge.Eplan.Adapters;\ninternal static class ApiTryDispatch\n{\n"
        + "    internal static string? Read(string group, StorableObject target, JObject parameters) => System.Convert.ToString(group switch\n    {\n"
        + string.Join("\n", Selected(ApiIndexGenerator.Data(root)).Select(s => "        " + Literal(s.Entry.Row.Group) + " => (object)((global::" + s.Entry.Type[2..] + ")target)." + s.Entry.Name
            + (s.Entry.Row.Kind == "method" ? "(" + string.Join(", ", s.Member.Parameters!.Select(p => "parameters[" + Literal(p.Name) + "]!.Value<bool>()")) + ")" : "") + ","))
        + "\n        _ => throw new System.InvalidOperationException(\"No compiled dispatch for this group and shape.\"),\n    }, System.Globalization.CultureInfo.InvariantCulture);\n}\n";
}
