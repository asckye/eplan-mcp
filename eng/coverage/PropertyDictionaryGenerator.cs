using System.Globalization;
using System.Text.Json;
using System.Text.RegularExpressions;
using EplanMcp.Coverage.Reporting;

namespace EplanMcp.Coverage;

/// <summary>Deterministic embedded facts/classifications; no EPLAN and no inference of runtime capabilities.</summary>
internal static class PropertyDictionaryGenerator
{
    internal const string SourcePath = "catalog/eplan-2026.0.3/data-dictionary.jsonl";
    internal const string RelativePath = "src/EplanMcp.Contracts/Generated/PropertyDictionary.g.tsv";

    internal static string Render(string root) => RenderRows(ApiCatalog.Lines(Path.Combine(root, SourcePath)));

    internal static string RenderRows(IEnumerable<JsonElement> rows)
    {
        string[] lines = rows.OrderBy(r => r.GetProperty("object").GetString(), StringComparer.Ordinal)
            .ThenBy(r => r.GetProperty("name").GetString(), StringComparer.Ordinal).Select(Row).ToArray();
        return "# Generated by eng/coverage generate; do not edit. Source: " + SourcePath
            + "\n# object\tformal_name\tpublic_id_or_empty\tobsolete\tread_classification\n"
            + string.Join("\n", lines) + "\n";
    }

    private static string Row(JsonElement row)
    {
        string objectType = row.GetProperty("object").GetString()!;
        string name = row.GetProperty("name").GetString()!;
        string id = row.TryGetProperty("value", out JsonElement value) ? value.GetString()! : string.Empty;
        bool obsolete = row.TryGetProperty("obsolete", out JsonElement flag) && flag.GetBoolean();
        string classification = Classify(name, id, obsolete);
        return string.Join("\t", objectType, name, id, obsolete ? "1" : "0", classification);
    }

    private static string Classify(string name, string id, bool obsolete)
    {
        if (id == "2000")
        {
            return "runtime_identifier";
        }

        if (name.StartsWith("PROPUSER_", StringComparison.Ordinal))
        {
            return "user_metadata";
        }

        if (Regex.IsMatch(name, "CREATOR|CUSTOMER|AUTHOR|RESPONSIBLE|^PART_ADDRESS_|COMPANY|_USER(?:_|$)|USERCODE|USERNAME|USEREMAIL|USERPHONE", RegexOptions.CultureInvariant))
        {
            return "personal";
        }

        if (Regex.IsMatch(name, "PATH|DIRECTORY|FILE|MACRO|FORMPLOT|PICTURE", RegexOptions.CultureInvariant))
        {
            return "path";
        }

        if (Regex.IsMatch(name, "PASSWORD|CREDENTIAL|TOKEN|SECRET|LICEN[CS]|DATABASE|CONNECTIONSTRING", RegexOptions.CultureInvariant))
        {
            return "restricted";
        }

        // Design 4.3/5: every public, non-obsolete row of this reviewed catalog version that no exclusion rule matches is
        // readable; rows a later catalog adds are absent from the shipped data and so stay refused until reviewed.
        return obsolete ? "obsolete" : int.TryParse(id, NumberStyles.None, CultureInfo.InvariantCulture, out _) ? "readable" : "no_public_id";
    }
}
